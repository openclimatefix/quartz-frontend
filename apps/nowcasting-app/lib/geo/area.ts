import { area } from "@turf/turf";
import type { FeatureCollection } from "geojson";

/**
 * Every feature's area in km², in feature order, measured once per boundary file.
 *
 * `turf.area` is a spherical-excess sum over every ring vertex — GB's GSP file is 9 MB of them —
 * so it must not run on a value tick, and it does not need to: a boundary file is an immutable
 * artefact that `loadGeoAsset` parses once and hands every caller the same object. Keying a
 * `WeakMap` on that object makes "once per geometry load" structural: a remount, a second map
 * or a region-list refresh finds the areas already measured, and the entry goes when the
 * geometry does.
 *
 * Measured in the browser rather than stamped into the files (PR 772's `areaKm2` property):
 * the files are regenerated by `scripts/build-geo-assets.mjs`, and a derived property there is
 * one more thing every regeneration has to remember to keep.
 */
const cache = new WeakMap<FeatureCollection, readonly number[]>();

export const featureAreasKm2 = (shapes: FeatureCollection): readonly number[] => {
  const cached = cache.get(shapes);
  if (cached) return cached;
  const areas = shapes.features.map((feature) => area(feature) / 1_000_000);
  cache.set(shapes, areas);
  return areas;
};
